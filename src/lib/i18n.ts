const builtin: Record<string, Record<Key, string>> = { "zh-CN": zh, "en-US": en };

/** 导入的语言包，按语言代码。可以覆盖内置语言的词条，也可以是一门新语言。 */
let packs: Record<string, LangPack> = {};

export function setLangPacks(list: LangPack[]) {
  packs = {};
  for (const pack of list) if (typeof pack._locale === "string") packs[pack._locale] = pack;
}

/** 可以选的语言：两种内置的，加上导入的。 */
export function languages(): { code: string; name: string; custom: boolean }[] {
  const out = [
    { code: "zh-CN", name: "中文", custom: "zh-CN" in packs },
    { code: "en-US", name: "English", custom: "en-US" in packs },
  ];
  for (const [code, pack] of Object.entries(packs)) {
    if (!(code in builtin)) out.push({ code, name: pack._name || code, custom: true });
  }
  return out;
}

/** 一种语言当前生效的全部文字，导出语言包时用。 */
export function effectivePack(language: Language): LangPack {
  const name = languages().find((l) => l.code === language)?.name ?? language;
  // 新语言没翻译到的词条用英文垫底
  return { _locale: language, _name: name, ...(builtin[language] ?? en), ...packs[language] };
}

export type Vars = Record<string, string | number>;
export type Translate = (key: Key, vars?: Vars) => string;

export function translate(language: Language, key: Key, vars?: Vars): string {
  const text = packs[language]?.[key] ?? builtin[language]?.[key] ?? en[key] ?? key;
  return vars ? text.replace(/\{(\w+)\}/g, (_, name: string) => String(vars[name] ?? "")) : text;
}

/** 把后端给出的错误变成一句能看懂的话。 */
export function errorText(language: Language, error: unknown): string {
  const raw = typeof error === "string" ? error : error instanceof Error ? error.message : String(error);
  const code = `error.${raw.split(":")[0].trim()}` as Key;
  if (code in zh) return translate(language, code);
  return translate(language, "error.generic", { message: raw });
}
